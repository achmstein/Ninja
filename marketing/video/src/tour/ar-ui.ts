// Prices after the number, as the apps write them: "185.00 ج.م".
const money = (n: string) => `${n} ج.م`;

// Translate a UI string: exact match first, then the patterns the screens build.
export const toArabic = (s: string): string => {
  if (s in AR_UI) return AR_UI[s];
  let m: RegExpMatchArray | null;
  if (s.includes(" · ")) return s.split(" · ").map(toArabic).join(" · ");
  if ((m = s.match(/^EGP ([\d.,]+)$/))) return money(m[1]);
  if ((m = s.match(/^EGP ([\d.,]+) (.+)$/))) return `${toArabic(m[2])} ${money(m[1])}`;
  if ((m = s.match(/^(.+?):? EGP ([\d.,]+)$/))) return `${toArabic(m[1])} ${money(m[2])}`;
  if ((m = s.match(/^(\d+)[x×] (.+)$/))) return `${m[1]}× ${toArabic(m[2])}`;
  if ((m = s.match(/^(\d+) items?$/))) return m[1] === "1" ? "صنف واحد" : `${m[1]} أصناف`;
  if ((m = s.match(/^(\d+) lines?$/))) return m[1] === "1" ? "صنف واحد" : `${m[1]} أصناف`;
  if ((m = s.match(/^(\d+) to prepare$/))) return `${m[1]} للتحضير`;
  if ((m = s.match(/^(\d+) pts to (.+)$/))) return `${m[1]} نقطة لـ ${toArabic(m[2])}`;
  if ((m = s.match(/^Order #(\d+)$/))) return `طلب #${m[1]}`;
  if ((m = s.match(/^Day starts (\d+):(\d+) AM$/))) return `اليوم يبدأ ${m[1].padStart(2, "0")}:${m[2]}`;
  if ((m = s.match(/^\+ (.+)$/))) return `+ ${toArabic(m[1])}`;
  if ((m = s.match(/^(.+): (.+)$/))) return `${toArabic(m[1])}: ${toArabic(m[2])}`;
  return s;
};
