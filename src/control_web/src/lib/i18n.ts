export type TranslationKey = keyof typeof dictionary

export type TranslateParams = Record<string, string | number>

const pluralRules = new Intl.PluralRules('en-US')

function format(entry: Message, params?: TranslateParams): string {
  let template: string
  if (typeof entry === 'string') {
    template = entry
  } else {
    const count = Number(params?.[entry.plural] ?? 0)
    template =
      entry.forms[`=${count}`] ??
      entry.forms[pluralRules.select(count)] ??
      entry.forms.other ??
      ''
  }
  if (!params) return template
  return template.replace(/\{(\w+)\}/g, (whole, name) =>
    name in params ? String(params[name]) : whole
  )
}

export function useT() {
  return (key: TranslationKey, params?: TranslateParams) =>
    format(dictionary[key], params)
}

// For code living outside the React tree (query-cache error handlers)
export function translate(
  key: TranslationKey,
  params?: TranslateParams
): string {
  return format(dictionary[key], params)
}

/** The BCP 47 tag every Intl formatter and toLocale*() call should use. */
export function useLocale(): string {
  return 'en-US'
}
